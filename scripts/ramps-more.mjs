// Spec 015: more color ramps, generated into packages/core/src/style/rampDataMore.ts. Nothing is invented here:
//   - the remaining ColorBrewer schemes (n-class lists), read from d3-scale-chromatic's data (ISC; the colors are
//     Copyright (c) 2002 Cynthia Brewer, Mark Harrower and The Pennsylvania State University, Apache-2.0);
//   - Tableau 10 (a flat 10-color categorical list, from d3-scale-chromatic) and Okabe & Ito's color-blind-safe 8 colors;
//   - Inferno, Cividis and Turbo, 11 evenly spaced anchors sampled from d3-scale-chromatic's interpolators
//     (Inferno and Cividis: CC0, from matplotlib / Nuñez et al.; Turbo: Apache-2.0, Google);
//   - Mako and Rocket (the perceptual maps viridisLite, and so mapgl, offers beside Viridis), 11 anchors sampled from
//     seaborn's lookup tables (BSD-3-Clause, Copyright (c) 2012-2023 Michael L. Waskom).
// The sources are not part of the repository. To regenerate, in an empty folder:
//   npm i d3-scale-chromatic
//   curl -L https://raw.githubusercontent.com/mwaskom/seaborn/master/seaborn/cm.py -o seaborn_cm.py
//   node scripts/ramps-more.mjs <that folder>
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = process.argv[2]
if (!src) throw new Error('Usage: node scripts/ramps-more.mjs <folder with node_modules/d3-scale-chromatic and seaborn_cm.py>')

const require = createRequire(path.join(path.resolve(src), 'x.js'))
const d3 = await import(pathToFileURL(require.resolve('d3-scale-chromatic')).href)
const { rgb } = await import(pathToFileURL(require.resolve('d3-color')).href)

const SCHEMES = ['BuGn', 'BuPu', 'GnBu', 'OrRd', 'PuBu', 'PuBuGn', 'PuRd', 'RdPu', 'YlGn', 'YlOrBr', 'Greys', 'PRGn', 'PuOr', 'RdGy', 'RdYlGn', 'Accent', 'Pastel1', 'Pastel2', 'Set3', 'Tableau10']
const brewer = {}
for (const name of SCHEMES) {
  const lists = d3[`scheme${name}`]
  if (!lists) throw new Error(`d3-scale-chromatic has no scheme${name}`)
  brewer[name] = {}
  if (typeof lists[0] === 'string') {
    // Qualitative schemes are one flat list.
    brewer[name][lists.length] = lists.map((c) => rgb(c).formatHex())
    continue
  }
  lists.forEach((colors, n) => {
    if (colors) brewer[name][n] = colors.map((c) => rgb(c).formatHex())
  })
}

// Okabe & Ito's color-blind-safe palette (M. Okabe and K. Ito, "Color Universal Design", 2008), as published.
brewer.OkabeIto = { 8: ['#e69f00', '#56b4e9', '#009e73', '#f0e442', '#0072b2', '#d55e00', '#cc79a7', '#000000'] }

const ANCHORS = 11
const sample = (f) => Array.from({ length: ANCHORS }, (_, i) => rgb(f(i / (ANCHORS - 1))).formatHex())
const perceptual = {
  inferno: sample(d3.interpolateInferno),
  cividis: sample(d3.interpolateCividis),
  turbo: sample(d3.interpolateTurbo),
}

const cm = fs.readFileSync(path.join(path.resolve(src), 'seaborn_cm.py'), 'utf8')
function lut(name) {
  const start = cm.indexOf(`_${name}_lut = [`)
  const end = cm.indexOf('\n]', start)
  const rows = [...cm.slice(start, end).matchAll(/\[\s*([\d.e+-]+)\s*,\s*([\d.e+-]+)\s*,\s*([\d.e+-]+)\s*\]/g)].map((m) => [m[1], m[2], m[3]].map(Number))
  if (rows.length !== 256) throw new Error(`${name}: ${rows.length} rows, expected 256`)
  return rows
}
for (const name of ['mako', 'rocket']) {
  const rows = lut(name)
  perceptual[name] = Array.from({ length: ANCHORS }, (_, i) => rgb(...rows[Math.round((i * 255) / (ANCHORS - 1))].map((v) => v * 255)).formatHex())
}

const fmt = (v) => JSON.stringify(v, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'").replace(/\[\n\s+('#[0-9a-f]{6}'(?:,\n\s+'#[0-9a-f]{6}')*)\n\s+\]/g, (_, list) => `[${list.replace(/,\n\s+/g, ', ')}]`)
const file = `// GENERATED by scripts/ramps-more.mjs (spec 015). Do not edit by hand.
// More ColorBrewer schemes (Copyright (c) 2002 Cynthia Brewer, Mark Harrower, and The Pennsylvania State University;
// Apache-2.0), read from d3-scale-chromatic (ISC). Inferno and Cividis (CC0) and Turbo (Apache-2.0, Google): 11 anchors
// from d3-scale-chromatic's interpolators. Mako and Rocket: 11 anchors from seaborn's lookup tables (BSD-3-Clause,
// Copyright (c) 2012-2023 Michael L. Waskom). See THIRD-PARTY-NOTICES.md.

/** ColorBrewer scheme -> class count -> colors. */
export const BREWER_MORE: Readonly<Record<string, Readonly<Record<number, readonly string[]>>>> = ${fmt(brewer)}

/** Perceptual colormaps: 11 evenly spaced anchors, low to high. */
export const PERCEPTUAL_MORE: Readonly<Record<string, readonly string[]>> = ${fmt(perceptual)}
`
fs.writeFileSync(path.join(root, 'packages/core/src/style/rampDataMore.ts'), file)
console.log('wrote packages/core/src/style/rampDataMore.ts', Object.keys(brewer).length, 'schemes', Object.keys(perceptual).join(', '))
