// Spec 015: the real sky behind the globe, generated into packages/ui/src/skyData.ts. Nothing is invented:
//   - the stars brighter than magnitude 5.2 (about 2,000) with their color index, from d3-celestial's stars.6.json, which is
//     built from the XHIP catalogue (an extended Hipparcos compilation; Anderson & Francis 2012, VizieR V/137D);
//   - the stick figures of the 88 IAU constellations from d3-celestial's constellations.lines.json (lines by Olaf Frohn);
//   - the Milky Way's five brightness outlines from d3-celestial's milkyway.json (the Milky Way Outline Catalog, Jose R.
//     Vieira, http://www.skymap.com/milkyway_cat.htm), thinned to a vertex about every degree of arc.
// d3-celestial is BSD-3-Clause, Copyright (c) 2015-2023 Olaf Frohn. To regenerate, in an empty folder:
//   npm i d3-celestial
//   node scripts/sky-data.mjs <that folder>
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = process.argv[2]
if (!src) throw new Error('Usage: node scripts/sky-data.mjs <folder with node_modules/d3-celestial>')
const data = path.join(path.resolve(src), 'node_modules', 'd3-celestial', 'data')
const read = (f) => JSON.parse(fs.readFileSync(path.join(data, f), 'utf8'))

const MAG_LIMIT = 5.2
const r1 = (v) => Math.round(v * 10) / 10

// Right ascension in degrees, 0..360 (the data holds -180..180).
const ra = (lon) => r1(((lon % 360) + 360) % 360)

const stars = []
for (const f of read('stars.6.json').features) {
  const mag = f.properties.mag
  if (mag > MAG_LIMIT) continue
  const bv = Number.parseFloat(f.properties.bv)
  stars.push([ra(f.geometry.coordinates[0]), r1(f.geometry.coordinates[1]), Math.round(mag * 10), Number.isFinite(bv) ? Math.round(bv * 10) : 5])
}
stars.sort((a, b) => a[2] - b[2])

const lines = []
for (const f of read('constellations.lines.json').features) {
  for (const part of f.geometry.coordinates) lines.push(part.flatMap(([lon, lat]) => [ra(lon), r1(lat)]))
}

// The Milky Way: levels (faintest outline first) of polygons of rings, each ring a flat list of right ascension and
// declination. A vertex is kept when it is at least STEP degrees of arc from the last kept one (the ring's own last vertex
// always is), which also makes the seam at right ascension 0 harmless.
const STEP = 1
const rad = Math.PI / 180
const arc = (a, b) => {
  const d = Math.sin(a[1] * rad) * Math.sin(b[1] * rad) + Math.cos(a[1] * rad) * Math.cos(b[1] * rad) * Math.cos((a[0] - b[0]) * rad)
  return Math.acos(Math.min(1, Math.max(-1, d))) / rad
}
function thin(ring) {
  const out = [ring[0]]
  for (let i = 1; i < ring.length - 1; i++) if (arc(out[out.length - 1], ring[i]) >= STEP) out.push(ring[i])
  out.push(ring[ring.length - 1])
  return out.length >= 4 ? out : null
}
// Each level is a list of closed rings (the file calls it a Polygon, with one ring per patch of sky); filled together,
// even-odd, so a ring inside another is a hole (a dark lane).
const milkyWay = read('milkyway.json')
  .features.sort((a, b) => a.id.localeCompare(b.id))
  .map((f) =>
    f.geometry.coordinates
      .map((ring) => thin(ring))
      .filter(Boolean)
      .map((ring) => ring.flatMap(([lon, lat]) => [ra(lon), r1(lat)]))
  )

const out = `// GENERATED by scripts/sky-data.mjs (spec 015). Do not edit by hand.
// Stars brighter than magnitude ${MAG_LIMIT} from d3-celestial's stars.6.json (built from XHIP, an extended Hipparcos compilation;
// Anderson & Francis 2012), the IAU constellation figures from its constellations.lines.json, and the Milky Way's outlines
// from its milkyway.json (Milky Way Outline Catalog, Jose R. Vieira). d3-celestial is BSD-3-Clause, Copyright (c) 2015-2023
// Olaf Frohn. See THIRD-PARTY-NOTICES.md.

/** Stars, brightest first: [right ascension (deg), declination (deg), magnitude x 10, B-V color index x 10]. */
export const STARS: ReadonlyArray<readonly [number, number, number, number]> = ${JSON.stringify(stars)}

/** Constellation figures: each a polyline as a flat list of right ascension and declination (deg). */
export const FIGURES: ReadonlyArray<readonly number[]> = ${JSON.stringify(lines)}

/** The Milky Way: five levels of brightness, faintest first; each a list of closed rings (filled even-odd); each ring a flat list of right ascension and declination (deg). */
export const MILKY_WAY: ReadonlyArray<ReadonlyArray<readonly number[]>> = ${JSON.stringify(milkyWay)}
`
fs.writeFileSync(path.join(root, 'packages/ui/src/skyData.ts'), out)
const rings = milkyWay.flat(1)
console.log('wrote packages/ui/src/skyData.ts:', stars.length, 'stars,', lines.length, 'figure lines,', milkyWay.map((l) => l.length).join('/'), 'milky way rings per level,', rings.reduce((n, r) => n + r.length / 2, 0), 'milky way vertices,', (out.length / 1024).toFixed(0), 'kB')
