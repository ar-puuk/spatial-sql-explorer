/** A Google Fonts family: the faces it has are a bit mask (1 regular, 2 bold, 4 italic, 8 bold italic). */
export interface GoogleFont {
  name: string;
  category: FontCategory;
  variants: number;
}

export const FACE_REGULAR = 1;
export const FACE_BOLD = 2;
export const FACE_ITALIC = 4;
export const FACE_BOLD_ITALIC = 8;

let catalog: Promise<readonly GoogleFont[]> | null = null;
let byName: Map<string, GoogleFont> | null = null;

/**
 * Every Google Fonts family, most popular first (generated by scripts/google-fonts-catalog.mjs). Loaded the first time it
 * is asked for, because it is only needed once the person has turned Google Fonts on.
 */
export function googleFontCatalog(): Promise<readonly GoogleFont[]> {
  catalog ??= import("./googleFontsCatalog.json").then((m) => {
    const rows = (m.default as [string, FontCategory, number][]).map(([name, category, variants]) => ({ name, category, variants }));
    byName = new Map(rows.map((f) => [f.name.toLowerCase(), f]));
    return rows;
  });
  return catalog;
}

const GENERIC: Record<FontCategory, string> = {
  sans: "sans-serif",
  serif: "serif",
  mono: "monospace",
  display: "sans-serif",
  handwriting: "cursive",
};

/** The default family: the system's own sans, as the print has always drawn. */
export const DEFAULT_FONT_STACK = "system-ui, -apple-system, sans-serif";

/** The system font with this name (case does not matter), if there is one. */
export function findSystemFont(name: string): SystemFont | undefined {
  const n = name.trim().toLowerCase();
  return SYSTEM_FONTS.find((f) => f.name.toLowerCase() === n);
}

/** The catalog's entry for a Google family (case does not matter): known once the catalog has been loaded. */
export function findGoogleFont(name: string): GoogleFont | undefined {
  return byName?.get(name.trim().toLowerCase());
}

/** Does the family come from Google Fonts (a name that is neither empty nor a system font)? */
export function isGoogleFamily(family: string): boolean {
  return family.trim() !== "" && !findSystemFont(family);
}

/** The CSS family list to draw a family with: a system font's stack, or the quoted name with a generic fallback. */
export function fontStack(family: string): string {
  const name = family.trim();
  if (!name) return DEFAULT_FONT_STACK;
  const system = findSystemFont(name);
  if (system) return system.stack;
  const category = findGoogleFont(name)?.category ?? "sans";
  return `"${name.replace(/["\\]/g, "")}", ${GENERIC[category]}`;
}
