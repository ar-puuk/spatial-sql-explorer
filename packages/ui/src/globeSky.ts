// Spec 008 (user request, 2026-10-11): the globe in space, after GeoLibre's
// design (a deep-space backdrop, a starfield that drifts with the view, an
// atmosphere glow around the earth, occasional comets). The glow is mostly our
// halo; MapLibre's sky atmosphere adds a faint lit rim. The backdrop and stars
// are drawn here on a canvas behind the map, which the globe projection leaves
// transparent around the earth; comets on a second canvas, never in exports.
// Decorative only: no data of the user's. Spec 015: every star the eye can see (about 5,000) and the Milky
// Way's outlines, where they really are at this moment: the device's clock gives the sidereal time, and the globe's camera
// looks through the Earth at the sky beyond it, so the Arctic and Polaris are never in one view (packages/ui/src/skyData.ts,
// generated by scripts/sky-data.mjs from d3-celestial, BSD-3-Clause).
// Comets adapted from GeoLibre packages/plugins/src/plugins/maplibre-effects.ts (MIT).
import { skyFrame } from '@spatial-explorer/core'
import type { Vec3 } from '@spatial-explorer/core'
import type { SkySpecification } from 'maplibre-gl'

/** How strongly MapLibre's lit atmosphere shows on the globe's rim (user request 2026-10-14: half of MapLibre's full glow; GeoLibre has none). */
const ATMOSPHERE = 0.5

/** MapLibre's atmosphere around the globe, fading out as the globe turns into a flat map (zoom 5–7). */
export const GLOBE_SKY: SkySpecification = {
  'sky-color': '#0b1a36',
  'horizon-color': '#9fd3ff',
  'atmosphere-blend': ['interpolate', ['linear'], ['zoom'], 0, ATMOSPHERE, 5, ATMOSPHERE, 7, 0],
}

/** Flat map: no atmosphere (MapLibre has no "no sky" value). */
export const FLAT_SKY: SkySpecification = { 'atmosphere-blend': 0 }

/** The globe's outline on screen. */
export interface GlobeCircle {
  x: number
  y: number
  r: number
}

/**
 * The globe's outline on screen: points just inside the horizon (88° from
 * the view's center), projected; their centroid and mean distance. Works
 * tilted too (an ellipse, approximated by a circle).
 */
export function globeCircle(center: { lng: number; lat: number }, project: (lngLat: [number, number]) => { x: number; y: number }): GlobeCircle | null {
  const rad = Math.PI / 180
  const d = 88 * rad
  const lat1 = center.lat * rad
  const lng1 = center.lng * rad
  const pts: Array<{ x: number; y: number }> = []
  for (let i = 0; i < 24; i++) {
    const b = (i / 24) * 2 * Math.PI
    const lat2 = Math.asin(Math.sin(lat1) * Math.cos(d) + Math.cos(lat1) * Math.sin(d) * Math.cos(b))
    const lng2 = lng1 + Math.atan2(Math.sin(b) * Math.sin(d) * Math.cos(lat1), Math.cos(d) - Math.sin(lat1) * Math.sin(lat2))
    const p = project([((lng2 / rad + 540) % 360) - 180, lat2 / rad])
    if (Number.isFinite(p.x) && Number.isFinite(p.y)) pts.push(p)
  }
  if (pts.length < 8) return null
  const x = pts.reduce((a, p) => a + p.x, 0) / pts.length
  const y = pts.reduce((a, p) => a + p.y, 0) / pts.length
  const r = pts.reduce((a, p) => a + Math.hypot(p.x - x, p.y - y), 0) / pts.length
  return r > 4 ? { x, y, r } : null
}

/** Deep-space colors: the center of the backdrop and its edges. Fixed, like data colors (not theme tokens). */
const SPACE_CENTER = '#0d1f3c'
const SPACE_EDGE = '#020610'
// --- The real sky ---------------------------------------------------------------------------------------------------

interface Sky {
  /** Unit vectors of the stars (x, y, z each), and per star its magnitude and tint. */
  starXyz: Float32Array
  mag: Float32Array
  tint: string[]
  /** Each figure as unit vectors of its vertices. */
  figures: Float32Array[]
  /** The Milky Way: per level of brightness (faintest first), its rings as unit vectors. */
  milkyWay: Float32Array[][]
}
let realSky: Sky | null = null
let loading = false
const RAD = Math.PI / 180

/** A direction from right ascension and declination (degrees), as a unit vector in the inertial frame. */
const unitFrom = (raDeg: number, decDeg: number, out: Float32Array, i: number): void => {
  const a = raDeg * RAD
  const d = decDeg * RAD
  out[i] = Math.cos(d) * Math.cos(a)
  out[i + 1] = Math.cos(d) * Math.sin(a)
  out[i + 2] = Math.sin(d)
}

/** A star's color from its B-V index: blue-white to white to orange. */
function tintOf(bv: number): string {
  if (bv < 0) return '176,205,255'
  if (bv < 0.5) return '240,244,255'
  if (bv < 0.9) return '255,244,220'
  if (bv < 1.3) return '255,216,170'
  return '255,184,130'
}

const pathOf = (flat: readonly number[]): Float32Array => {
  const v = new Float32Array((flat.length / 2) * 3)
  for (let i = 0; i < flat.length; i += 2) unitFrom(flat[i], flat[i + 1], v, (i / 2) * 3)
  return v
}

/**
 * Loads the stars, figures and Milky Way the first time the globe is shown (a chunk of its own); `onLoad` redraws the sky
 * then. Until it arrives the sky is the faint dust alone.
 */
export function loadSky(onLoad: () => void): void {
  if (realSky || loading) return
  loading = true
  void import('./skyData.js')
    .then(({ STARS, FIGURES, MILKY_WAY }) => {
      const starXyz = new Float32Array(STARS.length * 3)
      const mag = new Float32Array(STARS.length)
      const tint: string[] = []
      STARS.forEach(([ra, dec, m, bv], i) => {
        unitFrom(ra, dec, starXyz, i * 3)
        mag[i] = m / 10
        tint.push(tintOf(bv / 10))
      })
      realSky = { starXyz, mag, tint, figures: FIGURES.map(pathOf), milkyWay: MILKY_WAY.map((level) => level.map(pathOf)) }
      onLoad()
    })
    .catch(() => {
      loading = false
    })
}

/**
 * Whether the stars are joined into the constellations' stick figures. Off (user decision 2026-10-15: the lines look unnatural);
 * the figures stay in the data (skyData.ts FIGURES), so turning this on brings them back.
 */
const SHOW_CONSTELLATION_LINES = false

const TEX_W = 1024
const TEX_H = 512
/** Per level of brightness (faintest first), how much each outline adds. Kept x10 in the texture for precision. */
const LEVEL_ALPHA = [0.01, 0.014, 0.018, 0.022, 0.028]
const TEX_GAIN = 10
/** The Milky Way painted once in right ascension and declination: 0..1 brightness per texel, so it cannot change with the view. */
let milkyTexture: Float32Array | null = null

function buildMilkyTexture(sky: Sky): Float32Array {
  const canvas = document.createElement('canvas')
  canvas.width = TEX_W
  canvas.height = TEX_H
  const ctx = canvas.getContext('2d')
  const out = new Float32Array(TEX_W * TEX_H)
  if (!ctx) return out
  ctx.globalCompositeOperation = 'lighter'
  sky.milkyWay.forEach((rings, level) => {
    ctx.beginPath()
    for (const ring of rings) {
      // Unwrap right ascension so a ring crossing 0/360 stays one piece, and draw it a turn to either side too.
      const xs: number[] = []
      const ys: number[] = []
      let prev = 0
      for (let i = 0; i < ring.length; i += 3) {
        let ra = Math.atan2(ring[i + 1], ring[i]) / RAD
        if (i > 0) while (ra - prev > 180) ra -= 360
        if (i > 0) while (ra - prev < -180) ra += 360
        prev = ra
        xs.push((ra / 360) * TEX_W)
        ys.push(((90 - Math.asin(Math.max(-1, Math.min(1, ring[i + 2]))) / RAD) / 180) * TEX_H)
      }
      // A ring that goes once around the whole sky (the band's two edges) is open in this flat view: close it through the north
      // pole, not along a chord, which would be a straight band of its own. Two such edges then fill between them, even-odd.
      const around = Math.abs(xs[xs.length - 1] - xs[0]) > TEX_W / 2
      for (const shift of [-TEX_W, 0, TEX_W]) {
        xs.forEach((x, k) => (k ? ctx.lineTo(x + shift, ys[k]) : ctx.moveTo(x + shift, ys[k])))
        if (around) {
          ctx.lineTo(xs[xs.length - 1] + shift, 0)
          ctx.lineTo(xs[0] + shift, 0)
        }
        ctx.closePath()
      }
    }
    ctx.fillStyle = `rgba(255,255,255,${((LEVEL_ALPHA[level] ?? 0.02) * TEX_GAIN).toFixed(3)})`
    ctx.fill('evenodd')
  })
  const px = ctx.getImageData(0, 0, TEX_W, TEX_H).data
  for (let i = 0; i < out.length; i++) out[i] = px[i * 4 + 3] / 255 / TEX_GAIN
  return out
}

let milkyCanvas: HTMLCanvasElement | null = null

/** The Milky Way: for each (coarse) screen pixel, the sky direction it looks at, and the texture's brightness there. */
function drawMilkyWay(ctx: CanvasRenderingContext2D, w: number, h: number, focal: number, at: Vec3, right: Vec3, up: Vec3): void {
  if (!realSky) return
  milkyTexture ??= buildMilkyTexture(realSky)
  const tex = milkyTexture
  const STEP = 4
  const cw = Math.max(1, Math.ceil(w / STEP))
  const ch = Math.max(1, Math.ceil(h / STEP))
  milkyCanvas ??= document.createElement('canvas')
  if (milkyCanvas.width !== cw || milkyCanvas.height !== ch) {
    milkyCanvas.width = cw
    milkyCanvas.height = ch
  }
  const mctx = milkyCanvas.getContext('2d')
  if (!mctx) return
  const img = mctx.createImageData(cw, ch)
  const data = img.data
  for (let j = 0; j < ch; j++) {
    const b = (h / 2 - (j + 0.5) * STEP) / focal
    for (let i = 0; i < cw; i++) {
      const a = ((i + 0.5) * STEP - w / 2) / focal
      // The ray's direction in the sky: forward is away from the camera, through the Earth.
      const vx = a * right[0] + b * up[0] - at[0]
      const vy = a * right[1] + b * up[1] - at[1]
      const vz = a * right[2] + b * up[2] - at[2]
      const len = Math.hypot(vx, vy, vz)
      let ra = Math.atan2(vy, vx) / (2 * Math.PI)
      ra -= Math.floor(ra)
      const x = Math.min(TEX_W - 1, Math.floor(ra * TEX_W))
      const y = Math.min(TEX_H - 1, Math.floor(((Math.PI / 2 - Math.asin(vz / len)) / Math.PI) * TEX_H))
      const alpha = tex[y * TEX_W + x]
      const o = (j * cw + i) * 4
      data[o] = 185
      data[o + 1] = 200
      data[o + 2] = 235
      data[o + 3] = Math.min(255, alpha * 255)
    }
  }
  mctx.putImageData(img, 0, 0)
  ctx.save()
  ctx.globalCompositeOperation = 'lighter'
  ctx.imageSmoothingEnabled = true
  ctx.imageSmoothingQuality = 'high'
  ctx.drawImage(milkyCanvas, 0, 0, w, h)
  ctx.restore()
}

/**
 * The sky behind the Earth, as the globe's camera sees it. The camera hangs over the view's center (longitude, latitude),
 * looks at the Earth's center, with east to the right and north (turned by the bearing) up. Earth-fixed directions are turned
 * into the inertial frame by the sidereal time of the device's clock, so the stars are where they are tonight. What shows is
 * what lies beyond the Earth from there (a rectilinear view with MapLibre's own field of view, so the globe and the stars share
 * one camera); the stars on the camera's side of the Earth are behind the camera and are not seen. So Polaris is behind the
 * Earth only when you look from the southern hemisphere, and the Arctic and Polaris are never in one view.
 */
function drawRealSky(ctx: CanvasRenderingContext2D, w: number, h: number, center: { lng: number; lat: number }, bearing: number): void {
  const sky = realSky
  if (!sky) return
  const { at, right, up } = skyFrame(center, bearing, Date.now())
  // MapLibre's camera looks with a 36.87 degree vertical field of view.
  const focal = h / 2 / Math.tan((36.87 * RAD) / 2)
  const out = { x: 0, y: 0, ok: false }
  const COS_EDGE = Math.cos(80 * RAD)
  const project = (v: Float32Array, i: number): void => {
    const vx = v[i]
    const vy = v[i + 1]
    const vz = v[i + 2]
    const a = vx * right[0] + vy * right[1] + vz * right[2]
    const b = vx * up[0] + vy * up[1] + vz * up[2]
    // Forward is away from the camera's position, through the Earth.
    const d = -(vx * at[0] + vy * at[1] + vz * at[2])
    if (d < COS_EDGE) {
      out.ok = false
      return
    }
    out.x = w / 2 + (focal * a) / d
    out.y = h / 2 - (focal * b) / d
    out.ok = true
  }
  const trace = (v: Float32Array): void => {
    let pen = false
    for (let i = 0; i < v.length; i += 3) {
      project(v, i)
      if (out.ok) {
        if (pen) ctx.lineTo(out.x, out.y)
        else ctx.moveTo(out.x, out.y)
        pen = true
      } else pen = false
    }
  }

  drawMilkyWay(ctx, w, h, focal, at, right, up)

  // The constellations' figures (the stick figures joining the stars): off, they are a convention and not in the sky.
  if (SHOW_CONSTELLATION_LINES) {
    ctx.beginPath()
    for (const fig of sky.figures) trace(fig)
    ctx.lineWidth = 0.8
    ctx.strokeStyle = 'rgba(150,185,255,0.13)'
    ctx.stroke()
  }

  // The stars, sized by magnitude and tinted by color.
  for (let i = 0; i < sky.mag.length; i++) {
    project(sky.starXyz, i * 3)
    if (!out.ok || out.x < -8 || out.y < -8 || out.x > w + 8 || out.y > h + 8) continue
    const m = sky.mag[i]
    const r = 0.5 + Math.max(0, 5.2 - m) * 0.3
    const alpha = Math.min(0.95, 0.42 + (5.2 - m) * 0.14)
    const tint = sky.tint[i]
    if (m < 2.4) {
      const g = ctx.createRadialGradient(out.x, out.y, 0, out.x, out.y, r * 5)
      g.addColorStop(0, `rgba(${tint},0.22)`)
      g.addColorStop(1, `rgba(${tint},0)`)
      ctx.fillStyle = g
      ctx.fillRect(out.x - r * 5, out.y - r * 5, r * 10, r * 10)
    }
    ctx.fillStyle = `rgba(${tint},${alpha.toFixed(2)})`
    ctx.beginPath()
    ctx.arc(out.x, out.y, r, 0, Math.PI * 2)
    ctx.fill()
  }
}

/**
 * Paints the backdrop and the real sky into `canvas` (sized to its box).
 */
export function drawSky(canvas: HTMLCanvasElement, center: { lng: number; lat: number }, bearing: number, globe: GlobeCircle | null): void {
  const dpr = window.devicePixelRatio || 1
  const w = canvas.clientWidth
  const h = canvas.clientHeight
  if (!w || !h) return
  if (canvas.width !== Math.round(w * dpr) || canvas.height !== Math.round(h * dpr)) {
    canvas.width = Math.round(w * dpr)
    canvas.height = Math.round(h * dpr)
  }
  const ctx = canvas.getContext('2d')
  if (!ctx) return
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
  const bg = ctx.createRadialGradient(w / 2, h / 2, 0, w / 2, h / 2, Math.hypot(w, h) / 2)
  bg.addColorStop(0, SPACE_CENTER)
  bg.addColorStop(1, SPACE_EDGE)
  ctx.fillStyle = bg
  ctx.fillRect(0, 0, w, h)

  drawRealSky(ctx, w, h, center, bearing)

  // The earth's glow: a soft blue halo just outside the globe's edge (the globe covers the inside).
  if (globe) {
    const { x, y, r } = globe
    const halo = ctx.createRadialGradient(x, y, r * 0.96, x, y, r * 1.22)
    halo.addColorStop(0, 'rgba(150, 205, 255, 0.55)')
    halo.addColorStop(0.18, 'rgba(110, 175, 255, 0.32)')
    halo.addColorStop(0.5, 'rgba(70, 130, 230, 0.12)')
    halo.addColorStop(1, 'rgba(40, 90, 200, 0)')
    ctx.globalCompositeOperation = 'lighter'
    ctx.fillStyle = halo
    ctx.fillRect(x - r * 1.3, y - r * 1.3, r * 2.6, r * 2.6)
    ctx.globalCompositeOperation = 'source-over'
  }
}

/** One comet: where its head is, its heading and speed (CSS px per 60 Hz frame), its tail and its life (frames). */
interface Comet {
  x: number
  y: number
  angle: number
  speed: number
  len: number
  life: number
  maxLife: number
}

/** On average one comet every this many milliseconds (GeoLibre: about every 3 s; ours is subtler). */
const COMET_MEAN_GAP_MS = 7000
const FRAME_MS = 1000 / 60

/**
 * Occasional comets, drawn on their own canvas behind the map (so they pass
 * behind the globe). One at a time, faint and quick. Nothing runs between
 * comets: the next is a timer, and frames are drawn only while one is
 * crossing. None when the system asks for reduced motion.
 */
export class Comets {
  private comet: Comet | null = null
  private timer: ReturnType<typeof setTimeout> | null = null
  private frame = 0
  private last = 0
  private running = false

  constructor(private readonly canvas: HTMLCanvasElement) {}

  start(): void {
    if (this.running || matchMedia('(prefers-reduced-motion: reduce)').matches) return
    this.running = true
    this.schedule()
  }

  stop(): void {
    this.running = false
    if (this.timer) clearTimeout(this.timer)
    this.timer = null
    if (this.frame) cancelAnimationFrame(this.frame)
    this.frame = 0
    this.comet = null
    this.canvas.getContext('2d')?.clearRect(0, 0, this.canvas.width, this.canvas.height)
  }

  private schedule(): void {
    // Exponential gaps: comets come at random, not on a beat.
    const gap = -Math.log(1 - Math.random()) * COMET_MEAN_GAP_MS
    this.timer = setTimeout(() => {
      this.timer = null
      if (!this.running) return
      if (document.hidden) this.schedule()
      else this.spawn()
    }, gap)
  }

  private spawn(): void {
    const w = this.canvas.clientWidth
    const h = this.canvas.clientHeight
    if (!w || !h) {
      this.schedule()
      return
    }
    const dpr = window.devicePixelRatio || 1
    if (this.canvas.width !== Math.round(w * dpr) || this.canvas.height !== Math.round(h * dpr)) {
      this.canvas.width = Math.round(w * dpr)
      this.canvas.height = Math.round(h * dpr)
    }
    this.comet = {
      x: Math.random() * w,
      y: Math.random() * h,
      angle: Math.random() * Math.PI * 2,
      speed: 5 + Math.random() * 5,
      len: 90 + Math.random() * 110,
      life: 0,
      maxLife: 60 + Math.random() * 40,
    }
    this.last = performance.now()
    this.frame = requestAnimationFrame((t) => this.draw(t))
  }

  private draw(now: number): void {
    this.frame = 0
    const c = this.comet
    const ctx = this.canvas.getContext('2d')
    if (!c || !ctx || !this.running) return
    const step = Math.min((now - this.last) / FRAME_MS, 2)
    this.last = now
    c.life += step
    c.x += Math.cos(c.angle) * c.speed * step
    c.y += Math.sin(c.angle) * c.speed * step
    const dpr = window.devicePixelRatio || 1
    const w = this.canvas.width / dpr
    const h = this.canvas.height / dpr
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
    ctx.clearRect(0, 0, w, h)
    if (c.life >= c.maxLife || c.x < -c.len || c.x > w + c.len || c.y < -c.len || c.y > h + c.len) {
      this.comet = null
      this.schedule()
      return
    }
    // Fades in quickly and out slowly; at most half-bright (subtle).
    const t = c.life / c.maxLife
    const alpha = 0.5 * Math.min(1, t * 6) * (1 - t)
    const tx = c.x - Math.cos(c.angle) * c.len
    const ty = c.y - Math.sin(c.angle) * c.len
    const tail = ctx.createLinearGradient(tx, ty, c.x, c.y)
    tail.addColorStop(0, 'rgba(255, 255, 255, 0)')
    tail.addColorStop(1, `rgba(255, 255, 255, ${alpha.toFixed(3)})`)
    ctx.strokeStyle = tail
    ctx.lineWidth = 1
    ctx.beginPath()
    ctx.moveTo(tx, ty)
    ctx.lineTo(c.x, c.y)
    ctx.stroke()
    ctx.fillStyle = `rgba(200, 220, 255, ${(0.6 * alpha).toFixed(3)})`
    ctx.beginPath()
    ctx.arc(c.x, c.y, 1.5, 0, Math.PI * 2)
    ctx.fill()
    this.frame = requestAnimationFrame((n) => this.draw(n))
  }
}
